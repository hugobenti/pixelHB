/**
 * schema.org structured data for the home page, serialized for a `<script type="application/ld+json">`.
 * `WebSite` gives Google the site name for search results; `WebApplication` describes the free
 * editor. `<` is escaped so the JSON can never close the script tag.
 */
export const homeStructuredData = JSON.stringify({
  "@context": "https://schema.org",
  "@graph": [
    { "@type": "WebSite", name: site.name, url: `${site.url}/` },
    {
      "@type": "WebApplication",
      name: site.name,
      url: `${site.url}/`,
      description: home.metaDescription,
      applicationCategory: "DesignApplication",
      operatingSystem: "Any",
      browserRequirements: "Requires a modern browser with JavaScript enabled.",
      isAccessibleForFree: true,
      offers: { "@type": "Offer", price: "0", priceCurrency: "USD" },
      author: { "@type": "Person", name: site.author },
    },
  ],
}).replace(/</g, "\\u003c");
